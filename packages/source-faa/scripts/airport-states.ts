// This script writes `src/airports.ts`: the US state of each large and medium US airport, by its FAA location id.
// The input is the file `airports.csv` of OurAirports (github.com/davidmegginson/ourairports-data), under the Unlicense.
// Usage: node scripts/airport-states.ts <path of airports.csv>
import { readFileSync, writeFileSync } from "node:fs";

const path = process.argv[2];
if (path === undefined) throw new Error("usage: node scripts/airport-states.ts <path of airports.csv>");

/** This function splits one line of the CSV file. A field in quotes can hold a comma. */
function fields(line: string): string[] {
  const out: string[] = [];
  let field = "";
  let quoted = false;
  for (const char of line) {
    if (char === '"') quoted = !quoted;
    else if (char === "," && !quoted) {
      out.push(field);
      field = "";
    } else field += char;
  }
  out.push(field);
  return out;
}

const [head = [], ...rows] = readFileSync(path, "utf8").split(/\r?\n/).filter((line) => line !== "").map(fields);
const at = (name: string): number => {
  const index = head.indexOf(name);
  if (index < 0) throw new Error(`the CSV file has no column ${name}`);
  return index;
};
const [type, country, region, code] = [at("type"), at("iso_country"), at("iso_region"), at("local_code")];
const states = new Map<string, string>();
for (const row of rows) {
  if (row[country] !== "US" || !["large_airport", "medium_airport"].includes(row[type] ?? "")) continue;
  const id = row[code];
  const state = /^US-([A-Z]{2})$/.exec(row[region] ?? "")?.[1];
  if (id === undefined || !/^[A-Z0-9]{3,4}$/.test(id) || state === undefined) continue;
  if (states.has(id) && states.get(id) !== state) throw new Error(`the location id ${id} has two states`);
  states.set(id, state);
}
const pairs = [...states].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([id, state]) => `${id}:${state}`);
const lines = [];
for (let index = 0; index < pairs.length; index += 12) lines.push(`  "${pairs.slice(index, index + 12).join(" ")}",`);
writeFileSync(
  new URL("../src/airports.ts", import.meta.url),
  `/**
 * The US state of each large and medium US airport, by its FAA location id. The status of the FAA names each airport by
 * this id. The script \`scripts/airport-states.ts\` writes this file from the file \`airports.csv\` of OurAirports, which is
 * under the Unlicense (public domain). Do not edit this file by hand.
 */

/** The pairs of an id and a state, as \`ID:ST\` texts, in the order of the ids. */
const PAIRS: readonly string[] = [
${lines.join("\n")}
];

/** The US state of each airport, by its FAA location id. The table has ${String(pairs.length)} airports. */
export const AIRPORT_STATES: ReadonlyMap<string, string> = new Map(
  PAIRS.flatMap((line) => line.split(" ")).map((pair) => pair.split(":") as [string, string]),
);
`,
);
console.log(`airports: ${String(pairs.length)}`);
