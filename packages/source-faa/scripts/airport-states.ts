// This script writes `src/airports.ts`: the US state and the point of each large and medium US airport, by its FAA location id.
// The input is the file `airports.csv` of OurAirports (github.com/davidmegginson/ourairports-data), under the Unlicense.
// Usage: node scripts/airport-states.ts <path of airports.csv>
import { readFileSync, writeFileSync } from "node:fs";

const path = process.argv[2];
if (path === undefined) throw new Error("usage: node scripts/airport-states.ts <path of airports.csv>");

/** This function splits one line of the CSV file. A field in quotes can hold a comma. */
function fields(line: string): string[] {
  const out: string[] = [];
  let field = "";
  let quoted = false;
  for (const char of line) {
    if (char === '"') quoted = !quoted;
    else if (char === "," && !quoted) {
      out.push(field);
      field = "";
    } else field += char;
  }
  out.push(field);
  return out;
}

/** This function gives a coordinate in degrees with 3 decimals (approximately 100 m), or `undefined` for a value that is not a number in the range. */
function degrees(text: string | undefined, limit: number): string | undefined {
  const value = Number(text);
  if (text === undefined || text.trim() === "" || !Number.isFinite(value) || Math.abs(value) > limit) return undefined;
  return String(Math.round(value * 1000) / 1000);
}

const [head = [], ...rows] = readFileSync(path, "utf8").split(/\r?\n/).filter((line) => line !== "").map(fields);
const at = (name: string): number => {
  const index = head.indexOf(name);
  if (index < 0) throw new Error(`the CSV file has no column ${name}`);
  return index;
};
const [type, country, region, code, latitude, longitude] = [at("type"), at("iso_country"), at("iso_region"), at("local_code"), at("latitude_deg"), at("longitude_deg")];
const airports = new Map<string, string>();
for (const row of rows) {
  if (row[country] !== "US" || !["large_airport", "medium_airport"].includes(row[type] ?? "")) continue;
  const id = row[code];
  const state = /^US-([A-Z]{2})$/.exec(row[region] ?? "")?.[1];
  const lat = degrees(row[latitude], 90);
  const lon = degrees(row[longitude], 180);
  if (id === undefined || !/^[A-Z0-9]{3,4}$/.test(id) || state === undefined || lat === undefined || lon === undefined) continue;
  const entry = `${id}:${state}:${lat}:${lon}`;
  if (airports.has(id) && airports.get(id) !== entry) throw new Error(`the location id ${id} has two airports`);
  airports.set(id, entry);
}
const entries = [...airports].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([, entry]) => entry);
const lines = [];
for (let index = 0; index < entries.length; index += 6) lines.push(`  "${entries.slice(index, index + 6).join(" ")}",`);
writeFileSync(
  new URL("../src/airports.ts", import.meta.url),
  `/**
 * The US state and the point of each large and medium US airport, by its FAA location id. The status of the FAA names each
 * airport by this id. The script \`scripts/airport-states.ts\` writes this file from the file \`airports.csv\` of OurAirports,
 * which is under the Unlicense (public domain). Do not edit this file by hand.
 */

import type { Position } from "@mark1russell7/alerts";

/** The entries of the airports, as \`ID:ST:LAT:LON\` texts, in the order of the ids. Each coordinate has 3 decimals. */
const ENTRIES: readonly string[] = [
${lines.join("\n")}
];

/** The fields of each entry. */
const FIELDS: readonly (readonly [string, string, number, number])[] = ENTRIES.flatMap((line) => line.split(" ")).map((entry) => {
  const [id = "", state = "", lat = "", lon = ""] = entry.split(":");
  return [id, state, Number(lat), Number(lon)] as const;
});

/** The US state of each airport, by its FAA location id. The table has ${String(entries.length)} airports. */
export const AIRPORT_STATES: ReadonlyMap<string, string> = new Map(FIELDS.map(([id, state]) => [id, state]));

/** The point of each airport, by its FAA location id, as \`[longitude, latitude]\` in degrees. */
export const AIRPORT_POINTS: ReadonlyMap<string, Position> = new Map(FIELDS.map(([id, , lat, lon]) => [id, [lon, lat] as const]));
`,
);
console.log(`airports: ${String(entries.length)}`);
